#!/usr/bin/env node
/**
 * The photo library for the native apps (real photos, 2026-10-19; docs/runbooks/photos.md): src/photos/library.generated.ts
 * from web/packages/media — every processed photo of photos.json with its alt text, placeholder colour and the JPEG
 * variants of each crop (paths under the photos' base URL: the consumer site's /photos/ or a CDN), each slot's
 * fallback and the slug → category maps. The apps load the variants over the network (no image in the bundle).
 *
 * `make photos` runs it; `node scripts/gen-photos.mjs --check` (the kit's test) fails when the file is stale.
 * No dependencies: it runs before `pnpm install` too.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CROPS, processed, variants } from '../../../../web/packages/media/src/core.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const media = join(here, '../../../../web/packages/media');
const out = join(here, '../src/photos/library.generated.ts');
const read = (p) => JSON.parse(readFileSync(join(media, p), 'utf8'));

export function libraryFile(photos, runtime) {
  const library = {};
  for (const [slot, e] of Object.entries(photos).sort(([a], [b]) => a.localeCompare(b))) {
    if (!processed(e)) continue;
    const all = variants(slot, e).filter((v) => v.format === 'jpg');
    library[slot] = {
      alt: e.alt,
      width: e.width,
      height: e.height,
      placeholder: e.placeholder ?? null,
      focal: e.focal,
      sizes: Object.fromEntries(Object.keys(CROPS).map((crop) => [crop, all.filter((v) => v.crop === crop).map((v) => [v.width, v.height, v.path])])),
    };
  }
  const json = (v) => JSON.stringify(v);
  return [
    '// GENERATED by mobile/packages/mobile-kit/scripts/gen-photos.mjs from web/packages/media (photos.json, generated/runtime.json) — do not edit; `make photos`.',
    '',
    "export type Crop = 'square' | 'card' | 'wide';",
    '',
    '/** A photo of the library: what it shows, its size, its loading colour and its JPEG variants ([width, height, path]). */',
    'export interface LibraryPhoto {',
    '  alt: { en: string; fr: string };',
    '  width: number;',
    '  height: number;',
    '  placeholder: string | null;',
    '  focal: { x: number; y: number };',
    '  sizes: Record<Crop, [number, number, string][]>;',
    '}',
    '',
    `export const LIBRARY: Record<string, LibraryPhoto> = ${json(library)};`,
    '',
    '/** The slot shown in a slot\'s place while it has no photo (a category → its group → the landing\'s banner). */',
    `export const FALLBACK: Record<string, string> = ${json(runtime.fallback)};`,
    '',
    '/** Category ids by their slug (`plumber`, `bakery`) and the groups\', per half of the market. */',
    `export const SLUGS: Record<'service' | 'shop' | 'food', Record<string, string>> = ${json(runtime.slugs)};`,
    `export const GROUPS: Record<'service' | 'shop' | 'food', Record<string, string>> = ${json(runtime.groups)};`,
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const content = libraryFile(read('photos.json').photos, read('generated/runtime.json'));
  let current = null;
  try {
    current = readFileSync(out, 'utf8');
  } catch {
    // missing = stale
  }
  if (current === content) process.exit(0);
  if (process.argv.includes('--check')) {
    console.error(`stale: ${out} — run \`make photos\` (or node mobile/packages/mobile-kit/scripts/gen-photos.mjs)`);
    process.exit(1);
  }
  writeFileSync(out, content);
  console.log(`wrote ${out}`);
}
