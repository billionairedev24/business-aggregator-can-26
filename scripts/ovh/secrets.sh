#!/usr/bin/env bash
# OVHcloud targets (docs/runbooks/ovh.md § Secrets): the apps' and the data services' secrets as plain Kubernetes
# Secrets, written from ONE local file the operator keeps — .ovh/<target>.env (git-ignored, mode 600). OVHcloud has no
# secrets manager External Secrets could read, so this replaces Secret Manager + External Secrets of Google Cloud.
#
#   scripts/ovh/secrets.sh init  ovh-vps|ovh-mks   create the file: every generated secret filled in (random), the
#                                                  third-party ones (Stripe test keys, Twilio, registry) empty to fill
#   scripts/ovh/secrets.sh check ovh-vps|ovh-mks   which required keys are still empty (names only, never values)
#   scripts/ovh/secrets.sh apply ovh-vps|ovh-mks   write the Secrets into the cluster (kubectl's current context):
#       northline-secrets       every app variable that has a value (+ STORAGE_* keys and, with Managed PostgreSQL,
#                               DB_PASSWORD from Terraform's state)
#       northline-pg-app        CloudNativePG's owner credentials (in-cluster Postgres)
#       northline-valkey, northline-meilisearch   the in-cluster services' passwords (the same values the apps get)
#       northline-pg-backup-s3  the Postgres backup user's S3 keys (in-cluster Postgres)
#       northline-registry      image pull credentials, when REGISTRY_SERVER/USERNAME/PASSWORD are set
#       northline-demo-mail-auth  the demo inbox's basic-auth line (user demo, MAILPIT_PASSWORD), when
#                               OVH_DEMO_MAILPIT=true (S-155b, docs/runbooks/ovh.md § Email)
#     then restarts nothing: pods read Secrets at start (scripts/ovh/deploy.sh rolls them).
#
# Two sources (OVH_SECRETS_SOURCE):
#   file (default)  the operator's .ovh/<target>.env, as above
#   env             the pipeline (.github/workflows/ovh.yml): every key below from the environment variable of the same
#                   name (GitHub environment secrets/variables). A GENERATED key with no variable is taken from the
#                   cluster's Secret northline-generated, or generated once and kept there (never per run), so the
#                   same TOTP_KEY, KMS_LOCAL_KEY, BFF secrets and data-service passwords survive every redeploy. In
#                   GitHub Actions each generated value is masked (::add-mask::) before anything else runs.
#
# Values are never printed. Rotating one: edit the file, `apply`, then `kubectl -n northline-dryrun rollout restart
# deploy` (docs/runbooks/key-rotation.md for what each key protects). Losing the file loses nothing that can't be
# re-made, but TOTP_KEY and KMS_LOCAL_KEY changes invalidate enrolled authenticators' sealing and stored calendar tokens.
set -euo pipefail
. "$(dirname "$0")/common.sh"

cmd=${1:-}; ovh_target "${2:-}"

# Required by the dry-run values (secretEnv true) — must hold a value before `apply`. Stripe is optional for a first
# demo: without STRIPE_SECRET_KEY the api uses its fake payment gateway and scripts/ovh/deploy.sh switches identity and
# age checks to the local fakes (docs/runbooks/ovh.md § Today); with it, STRIPE_PUBLISHABLE_KEY is required too.
REQUIRED="TOTP_KEY WEBHOOK_SECRET_KEY KMS_LOCAL_KEY STUDIO_BFF_SECRET STUDIO_BFF_SECRET_HASH CONSUMER_BFF_SECRET
CONSUMER_BFF_SECRET_HASH CONSOLE_BFF_SECRET CONSOLE_BFF_SECRET_HASH DB_PASSWORD MEILISEARCH_API_KEY"
# Generated by `init` (file) or on the first `apply` (env); every one may also be given.
GENERATED="TOTP_KEY WEBHOOK_SECRET_KEY EMAIL_UNSUBSCRIBE_KEY KMS_LOCAL_KEY STUDIO_BFF_SECRET STUDIO_BFF_SECRET_HASH
CONSUMER_BFF_SECRET CONSUMER_BFF_SECRET_HASH CONSOLE_BFF_SECRET CONSOLE_BFF_SECRET_HASH DB_PASSWORD REDIS_PASSWORD
MEILISEARCH_API_KEY MAILPIT_PASSWORD"
# Third-party values, always given (empty = that integration stays on its dev fake or off).
PROVIDED="STRIPE_SECRET_KEY STRIPE_PUBLISHABLE_KEY STRIPE_WEBHOOK_SECRET STRIPE_CONNECT_WEBHOOK_SECRET SMS_AUTH_TOKEN
SMS_ACCOUNT_ID SMS_FROM EMAIL_API_KEY SMTP_HOST SMTP_PORT SMTP_USERNAME SMTP_PASSWORD SMTP_STARTTLS EMAIL_FROM
KAFKA_SASL_JAAS_CONFIG REGISTRY_SERVER REGISTRY_USERNAME REGISTRY_PASSWORD"
# Settings kept in the same file that are not app secrets (never copied into northline-secrets).
NOT_APP="SMS_FROM SMS_ACCOUNT_ID REGISTRY_SERVER REGISTRY_USERNAME REGISTRY_PASSWORD MAILPIT_PASSWORD SMTP_HOST SMTP_PORT
SMTP_USERNAME SMTP_STARTTLS EMAIL_FROM"
GENERATED_SECRET=northline-generated
SOURCE=${OVH_SECRETS_SOURCE:-file}
case "$SOURCE" in (file | env) ;; (*) die "OVH_SECRETS_SOURCE must be file or env (got '$SOURCE')" ;; esac

rand_b64() { openssl rand -base64 32; }
rand_hex() { openssl rand -hex 20; }        # URL-, shell- and Valkey-ACL-safe
bcrypt() {
  if command -v htpasswd >/dev/null 2>&1; then htpasswd -bnBC 12 "" "$1"
  else docker run --rm httpd:2.4-alpine htpasswd -bnBC 12 "" "$1"
  fi | tr -d ':\n' | sed 's/^/{bcrypt}/'
}

init() {
  need openssl
  [ ! -e "$OVH_ENV_FILE" ] || die "$OVH_ENV_FILE exists — edit it, or move it away to start over"
  mkdir -p "$(dirname "$OVH_ENV_FILE")"
  umask 077
  local s_studio s_consumer s_console h_studio h_consumer h_console h
  s_studio=$(rand_b64); s_consumer=$(rand_b64); s_console=$(rand_b64)
  h_studio=$(bcrypt "$s_studio"); h_consumer=$(bcrypt "$s_consumer"); h_console=$(bcrypt "$s_console")
  for h in "$h_studio" "$h_consumer" "$h_console"; do
    case "$h" in ('{bcrypt}$2'*) ;; (*) die "bcrypt failed (htpasswd, or Docker with httpd:2.4-alpine, is needed)" ;; esac
  done
  {
    echo "# Northline $OVH_TARGET secrets (docs/runbooks/ovh.md § Secrets). KEY=value, taken literally; never commit."
    echo "# Where (S-160): us-east-va (Vint Hill) or us-west-or (Hillsboro) on an OVHcloud US account — fake demo data on"
    echo "# the dev profile only — or ca-bhs (Beauharnois) on an OVHcloud Canada account. Not an app secret."
    echo "OVH_LOCATION=${OVH_LOCATION:-us-east-va}"
    echo "# Generated:"
    echo "TOTP_KEY=$(rand_b64)"
    echo "WEBHOOK_SECRET_KEY=$(rand_b64)"
    echo "EMAIL_UNSUBSCRIBE_KEY=$(rand_b64)"
    echo "KMS_LOCAL_KEY=$(rand_b64)"
    echo "STUDIO_BFF_SECRET=$s_studio"
    echo "STUDIO_BFF_SECRET_HASH=$h_studio"
    echo "CONSUMER_BFF_SECRET=$s_consumer"
    echo "CONSUMER_BFF_SECRET_HASH=$h_consumer"
    echo "CONSOLE_BFF_SECRET=$s_console"
    echo "CONSOLE_BFF_SECRET_HASH=$h_console"
    echo "# In-cluster data services (with Managed PostgreSQL, DB_PASSWORD comes from Terraform instead; an external"
    echo "# service: its provider's credential here)."
    echo "DB_PASSWORD=$(rand_hex)"
    echo "REDIS_PASSWORD=$(rand_hex)"
    echo "MEILISEARCH_API_KEY=$(rand_hex)"
    echo "# The demo inbox's password (user demo) when OVH_DEMO_MAILPIT=true (docs/runbooks/ovh.md § Email)."
    echo "MAILPIT_PASSWORD=$(rand_hex)"
    echo "# Stripe TEST mode (docs/runbooks/stripe.md): sk_test_…, pk_test_…; the webhook secrets after the webhooks step."
    echo "STRIPE_SECRET_KEY="
    echo "STRIPE_PUBLISHABLE_KEY="
    echo "STRIPE_WEBHOOK_SECRET="
    echo "STRIPE_CONNECT_WEBHOOK_SECRET="
    echo "# Twilio for northline-auth's SMS codes (needed to register anyone under the dev profile — demo.md § 2):"
    echo "# all three set = SMS_PROVIDER=twilio."
    echo "SMS_AUTH_TOKEN="
    echo "SMS_ACCOUNT_ID="
    echo "SMS_FROM="
    echo "# Email (docs/runbooks/ovh.md § Email) — one of: an SMTP relay (port 587 with STARTTLS; EMAIL_FROM = a sender the"
    echo "# relay accepts), the demo inbox (OVH_DEMO_MAILPIT=true: nothing is delivered, read the codes at mail.<domain>),"
    echo "# a SendGrid API key (EMAIL_API_KEY). None = the emails, codes included, are only in the apps' logs."
    echo "SMTP_HOST="
    echo "SMTP_PORT=587"
    echo "SMTP_USERNAME="
    echo "SMTP_PASSWORD="
    echo "SMTP_STARTTLS=true"
    echo "EMAIL_FROM="
    echo "OVH_DEMO_MAILPIT=false"
    echo "EMAIL_API_KEY="
    echo "# External Kafka with SASL only: the whole JAAS line."
    echo "KAFKA_SASL_JAAS_CONFIG="
    echo "# Private image registry (e.g. ghcr.io + a read:packages token); empty = public images."
    echo "REGISTRY_SERVER="
    echo "REGISTRY_USERNAME="
    echo "REGISTRY_PASSWORD="
  } >"$OVH_ENV_FILE"
  chmod 600 "$OVH_ENV_FILE"
  echo "wrote $OVH_ENV_FILE (mode 600). Fill in the Stripe test keys (and Twilio), then: make ovh-secrets TARGET=$OVH_TARGET"
}

managed_pg() {
  [ "$OVH_TARGET" = ovh-mks ] || return 1
  [ "$(tf_out postgres_credentials 'if . == null then "no" else "yes" end' 2>/dev/null || echo no)" = yes ]
}

# check [skip-generated] — the required keys with no value (names only). skip-generated: the env source before the
# cluster is reachable (the generated keys are made by `apply`).
check() {
  local k missing='' from=$OVH_ENV_FILE
  if [ "$SOURCE" = env ]; then from="the environment"
  else [ -f "$OVH_ENV_FILE" ] || die "no $OVH_ENV_FILE — run: scripts/ovh/secrets.sh init $OVH_TARGET"
  fi
  for k in $REQUIRED; do
    if [ "$k" = DB_PASSWORD ] && [ "${MANAGED_PG:-no}" = yes ]; then continue; fi
    if [ "${1:-}" = skip-generated ] && in_list "$k" "$GENERATED"; then continue; fi
    [ -n "$(env_get "$k")" ] || missing="$missing $k"
  done
  if [ -n "$(env_get SMTP_HOST)" ] && [ -n "$(env_get SMTP_USERNAME)" ] && [ -z "$(env_get SMTP_PASSWORD)" ]; then
    missing="$missing SMTP_PASSWORD"
  fi
  case "$(env_get STRIPE_SECRET_KEY)" in
    (sk_live_* | rk_live_*) die "STRIPE_SECRET_KEY is a live key: the dry run uses Stripe test mode only" ;;
    ("") echo "Stripe: no STRIPE_SECRET_KEY — the fake payment gateway, identity and age checks on the local fakes" ;;
    (*) [ -n "$(env_get STRIPE_PUBLISHABLE_KEY)" ] || missing="$missing STRIPE_PUBLISHABLE_KEY" ;;
  esac
  if [ -n "$missing" ]; then echo "empty in $from:$missing" >&2; return 1; fi
  echo "$from: every required key has a value"
}

in_list() { case " $(printf '%s' "$2" | tr '\n' ' ') " in (*" $1 "*) return 0 ;; esac; return 1; }

# mask <value> — hide a generated value from the GitHub Actions log before it can appear anywhere.
mask() { if [ "${GITHUB_ACTIONS:-}" = true ] && [ -n "$1" ]; then echo "::add-mask::$1"; fi; }

# stored <file> <KEY> — a value from a KEY=value file (northline-generated's contents).
stored() { awk -v k="$2" 'index($0, k "=") == 1 { print substr($0, length(k) + 2); exit }' "$1"; }

# materialize <out file> — the env source as a secrets file (the file source's format): every key from its variable;
# a generated key without one from the cluster's northline-generated, else generated now; northline-generated is
# written back when something was generated. Needs the namespace and kubectl.
materialize() {
  local out=$1 store="$tmp/generated.env" keep="$tmp/keep.env" k v pair_secret made=no json
  json=$(kubectl -n "$OVH_NAMESPACE" get secret "$GENERATED_SECRET" --ignore-not-found -o json) \
    || die "kubectl could not read secret/$GENERATED_SECRET (not regenerating anything over a connection error)"
  if [ -n "$json" ]; then printf '%s' "$json" | jq -r '.data // {} | to_entries[] | "\(.key)=\(.value | @base64d)"' >"$store"
  else : >"$store"
  fi
  : >"$out"; : >"$keep"
  for k in $GENERATED $PROVIDED; do
    v=$(env_get "$k")
    if [ -z "$v" ] && in_list "$k" "$GENERATED"; then
      case "$k" in
        (*_BFF_SECRET_HASH)
          # the hash of the secret actually used (written just above, the pair's secret comes first in GENERATED)
          pair_secret=$(stored "$out" "${k%_HASH}")
          if [ "$(stored "$store" "${k%_HASH}")" = "$pair_secret" ]; then v=$(stored "$store" "$k"); fi
          if [ -z "$v" ]; then
            v=$(bcrypt "$pair_secret"); made=yes
            case "$v" in ('{bcrypt}$2'*) ;; (*) die "bcrypt failed (htpasswd, or Docker with httpd:2.4-alpine, is needed)" ;; esac
          fi
          # keep the secret next to its hash (also one given by the environment), so the next run reuses the hash
          [ -n "$(stored "$keep" "${k%_HASH}")" ] || printf '%s=%s\n' "${k%_HASH}" "$pair_secret" >>"$keep" ;;
        (*)
          v=$(stored "$store" "$k")
          if [ -z "$v" ]; then
            case "$k" in (DB_PASSWORD | REDIS_PASSWORD | MEILISEARCH_API_KEY) v=$(rand_hex) ;; (*) v=$(rand_b64) ;; esac
            made=yes
          fi ;;
      esac
      mask "$v"
      printf '%s=%s\n' "$k" "$v" >>"$keep"
    fi
    [ -z "$v" ] || printf '%s=%s\n' "$k" "$v" >>"$out"
  done
  if [ "$made" = yes ]; then
    put_secret "$GENERATED_SECRET" "$keep"
    echo "   generated secrets kept in secret/$GENERATED_SECRET (back it up: docs/runbooks/ovh.md § Secrets)"
  fi
}

# put_secret <name> <env file> [kubectl args…] — create or update a Secret from an env file without printing it.
put_secret() {
  local name=$1 file=$2; shift 2
  kubectl -n "$OVH_NAMESPACE" create secret generic "$name" --from-env-file="$file" "$@" --dry-run=client -o yaml \
    | kubectl -n "$OVH_NAMESPACE" apply -f - >/dev/null
  echo "secret/$name written ($(grep -c . "$file") keys)"
}

apply() {
  need kubectl terraform jq openssl
  MANAGED_PG=no; if managed_pg; then MANAGED_PG=yes; fi
  local in_pg in_cache in_search
  tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
  umask 077
  in_pg=$(tf_out in_cluster .postgres); in_cache=$(tf_out in_cluster .cache); in_search=$(tf_out in_cluster .search)
  kubectl get namespace "$OVH_NAMESPACE" >/dev/null 2>&1 || kubectl create namespace "$OVH_NAMESPACE" >/dev/null
  local mailpit=${OVH_DEMO_MAILPIT:-$(env_get OVH_DEMO_MAILPIT)}
  if [ "$mailpit" = true ] && [ "$SOURCE" = file ] && [ -z "$(env_get MAILPIT_PASSWORD)" ]; then
    printf 'MAILPIT_PASSWORD=%s\n' "$(rand_hex)" >>"$OVH_ENV_FILE"
    echo "   MAILPIT_PASSWORD generated into $OVH_ENV_FILE (the demo inbox's password, user demo)"
  fi
  if [ "$SOURCE" = env ]; then
    # From here on the env source is a file like the operator's: the rest of apply reads it the same way.
    materialize "$tmp/from-env.env"
    OVH_ENV_FILE="$tmp/from-env.env"; OVH_SECRETS_SOURCE="file"
  fi
  check

  # northline-secrets: every non-empty app key from the file, then Terraform's.
  # The pipeline's own settings (OVH_*, TF_STATE_*, REGISTRY*: scripts/ovh/gh-setup.sh reads them from the same file)
  # never reach the apps.
  awk -F= -v skip=" $(printf '%s' "$NOT_APP" | tr '\n' ' ') " '/^[A-Z][A-Z0-9_]*=./ && $1 !~ /^(OVH_|TF_STATE_|REGISTRY)/ { if (index(skip, " " $1 " ") == 0) print }' \
    "$OVH_ENV_FILE" >"$tmp/app.env"
  if [ "$MANAGED_PG" = yes ]; then
    grep -v '^DB_PASSWORD=' "$tmp/app.env" >"$tmp/app2.env" || true; mv "$tmp/app2.env" "$tmp/app.env"
    printf 'DB_PASSWORD=%s\n' "$(tf_out postgres_credentials .app_password)" >>"$tmp/app.env"
  fi
  printf 'STORAGE_ACCESS_KEY=%s\nSTORAGE_SECRET_KEY=%s\n' "$(tf_out s3_credentials '.uploads.access_key_id')" \
    "$(tf_out s3_credentials '.uploads.secret_access_key')" >>"$tmp/app.env"
  put_secret northline-secrets "$tmp/app.env"

  if [ "$in_pg" = true ]; then
    printf 'username=%s\npassword=%s\n' "$(tf_out config_env .DB_USER)" "$(env_get DB_PASSWORD)" >"$tmp/pg.env"
    put_secret northline-pg-app "$tmp/pg.env" --type=kubernetes.io/basic-auth
    printf 'ACCESS_KEY_ID=%s\nACCESS_SECRET_KEY=%s\nREGION=%s\n' "$(tf_out s3_credentials '.["pg-backups"].access_key_id')" \
      "$(tf_out s3_credentials '.["pg-backups"].secret_access_key')" "$(tf_out s3_credentials '.["pg-backups"].region')" >"$tmp/s3.env"
    put_secret northline-pg-backup-s3 "$tmp/s3.env"
  fi
  if [ "$in_cache" = true ]; then
    printf 'REDIS_PASSWORD=%s\n' "$(env_get REDIS_PASSWORD)" >"$tmp/valkey.env"; put_secret northline-valkey "$tmp/valkey.env"
  fi
  if [ "$in_search" = true ]; then
    printf 'MEILISEARCH_API_KEY=%s\n' "$(env_get MEILISEARCH_API_KEY)" >"$tmp/meili.env"; put_secret northline-meilisearch "$tmp/meili.env"
  fi

  if [ -n "$(env_get REGISTRY_SERVER)" ] && [ -n "$(env_get REGISTRY_PASSWORD)" ]; then
    kubectl -n "$OVH_NAMESPACE" create secret docker-registry northline-registry --docker-server="$(env_get REGISTRY_SERVER)" \
      --docker-username="$(env_get REGISTRY_USERNAME)" --docker-password="$(env_get REGISTRY_PASSWORD)" \
      --dry-run=client -o yaml | kubectl -n "$OVH_NAMESPACE" apply -f - >/dev/null
    echo "secret/northline-registry written"
  fi

  if [ "$mailpit" = true ]; then
    local line
    if command -v htpasswd >/dev/null 2>&1; then line=$(htpasswd -bnBC 12 demo "$(env_get MAILPIT_PASSWORD)")
    else line=$(docker run --rm httpd:2.4-alpine htpasswd -bnBC 12 demo "$(env_get MAILPIT_PASSWORD)")
    fi
    line=$(printf '%s' "$line" | tr -d '\n')
    case "$line" in ('demo:$2'*) ;; (*) die "htpasswd failed for the demo inbox" ;; esac
    printf '%s\n' "$line" >"$tmp/htpasswd"
    kubectl -n "$OVH_NAMESPACE" create secret generic northline-demo-mail-auth --from-file=htpasswd="$tmp/htpasswd" \
      --dry-run=client -o yaml | kubectl -n "$OVH_NAMESPACE" apply -f - >/dev/null
    echo "secret/northline-demo-mail-auth written (user demo)"
  fi
}

case "$cmd" in
  init) [ "$SOURCE" = file ] || die "init writes the file source; the env source generates on apply"; init ;;
  check)
    MANAGED_PG=no; if managed_pg; then MANAGED_PG=yes; fi
    if [ "$SOURCE" = env ]; then check skip-generated; else check; fi ;;
  apply) apply ;;
  *) die "usage: $0 init|check|apply ovh-vps|ovh-mks" ;;
esac
