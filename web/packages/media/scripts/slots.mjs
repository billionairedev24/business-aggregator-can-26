#!/usr/bin/env node
// The photo slots (docs/runbooks/photos.md): every place the web and the apps show a stock photo, generated from the
// catalogue seed (db/seed/categories.json: one slot per group and leaf), the cuisine codes and fixed slots
// (slots.config.json) and the demo marketplace (scripts/demo/data/marketplace.json `photo`), so nothing is missed.
//
//   node scripts/slots.mjs            write generated/slots.json (the list, for people and tools) and
//                                     generated/runtime.json (each slot's fallback and the slug → category maps the
//                                     pages need)
//   node scripts/slots.mjs --check    fail when either file is out of date (pnpm test)
//   node scripts/slots.mjs --missing  the slots without a photo yet, by group, and the count (make photos-slots)
//   node scripts/slots.mjs --todo     the same as JSON lines: slot, what to search for, where it shows
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { processed } from '../src/core.mjs';

const HERE = join(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = join(HERE, '..', '..', '..');
const read = path => JSON.parse(readFileSync(path, 'utf8'));

/** CategorySeeder.slug (server/api/src/tools): the catalogue's ids are built from the names this way. */
export const slug = name => name.toLowerCase().replaceAll('&', 'and').replaceAll('é', 'e').replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');

const ROOT_BANNER = { service: 'banner/services', shop: 'banner/shop', food: 'banner/food' };
const ROOT_USE = { service: 'Services pages and cards', shop: 'Shop departments and product cards', food: 'Food pages and kitchens' };

export function build({ categories, config, marketplace }) {
  const slots = [];
  const fallback = {};
  const slugs = { service: {}, shop: {}, food: {} };
  const groups = { service: {}, shop: {}, food: {} };
  const add = (slot, s) => {
    if (slots.some(x => x.slot === slot)) throw new Error(`${slot}: listed twice`);
    slots.push({ slot, ...s });
    if (s.fallback) fallback[slot] = s.fallback;
  };

  for (const f of config.fixed) add(f.slot, { group: f.slot.split('/')[0], label: f.slot, query: f.hint, use: f.use, fallback: f.fallback });
  const hints = config.categoryHints ?? {};
  for (const root of ['service', 'shop', 'food']) {
    for (const g of categories[root]) {
      const groupId = `${root}.${slug(g.group)}`;
      groups[root][slug(g.group)] = groupId;
      add(`category/${groupId}`, { group: 'category', label: g.group, query: hints[groupId] ?? g.group, use: `${ROOT_USE[root]} (the group; each of its categories falls back to it)`, fallback: ROOT_BANNER[root] });
      for (const [name] of g.items) {
        const id = `${groupId}.${slug(name)}`;
        slugs[root][slug(name)] = id;
        add(`category/${id}`, { group: 'category', label: name, query: hints[id] ?? name.replace(/[·&/]/g, ' ').replace(/\s+/g, ' '), use: ROOT_USE[root], fallback: `category/${groupId}` });
      }
    }
  }
  for (const c of config.cuisines.codes) add(`cuisine/${c.code}`, { group: 'cuisine', label: c.code, query: c.hint, use: 'Food page cuisine tiles and kitchen covers', fallback: 'banner/food' });

  for (const m of marketplace.merchants) {
    if (!m.photo) throw new Error(`demo merchant ${m.key}: no photo slot`);
    add(m.photo, { group: 'demo', label: m.name, query: m.query ?? `${slots.find(x => x.slot === `category/${m.categories?.[0]}`)?.query ?? m.name} ${m.type === 'provider' ? 'at work' : 'shop'}`, use: `demo ${m.type}: its logo on the business page`, fallback: m.categories?.[0] ? `category/${m.categories[0]}` : undefined });
    for (const l of m.listings ?? []) {
      if (!l.photo) throw new Error(`demo listing ${m.key}.${l.key}: no photo slot`);
      add(l.photo, { group: 'demo', label: l.title, query: l.query ?? l.title.split(',')[0], use: `demo ${l.kind}: its listing photo (uploaded by make demo-data)`, fallback: l.category ? `category/${l.category}` : undefined });
    }
  }
  const known = new Set(slots.map(s => s.slot));
  for (const s of slots) if (s.fallback && !known.has(s.fallback)) throw new Error(`${s.slot}: falls back to ${s.fallback}, which is not a slot`);
  for (const id of Object.keys(hints)) if (!id.startsWith('$') && !known.has(`category/${id}`)) throw new Error(`categoryHints: ${id} is not a category`);
  return {
    slots: { $comment: 'GENERATED by web/packages/media/scripts/slots.mjs — do not edit; `make photos-slots` lists the ones without a photo.', count: slots.length, slots },
    runtime: { $comment: 'GENERATED by web/packages/media/scripts/slots.mjs — do not edit.', fallback, slugs, groups },
  };
}

function inputs() {
  return {
    categories: read(join(REPO, 'db', 'seed', 'categories.json')),
    config: read(join(HERE, 'slots.config.json')),
    marketplace: read(join(REPO, 'scripts', 'demo', 'data', 'marketplace.json')),
  };
}

const json = v => JSON.stringify(v, null, 1) + '\n';

function main(args) {
  const { slots, runtime } = build(inputs());
  const files = { [join(HERE, 'generated', 'slots.json')]: json(slots), [join(HERE, 'generated', 'runtime.json')]: json(runtime) };
  if (args.includes('--check')) {
    const stale = Object.entries(files).filter(([path, text]) => { try { return readFileSync(path, 'utf8') !== text; } catch { return true; } });
    if (stale.length) {
      console.error(`photo slots out of date: ${stale.map(([p]) => p.slice(HERE.length + 1)).join(', ')} — run make photos-slots (or pnpm --filter @northline/media slots)`);
      process.exit(1);
    }
    console.log(`photo slots up to date (${slots.count})`);
    return;
  }
  for (const [path, text] of Object.entries(files)) writeFileSync(path, text);
  if (!args.includes('--missing') && !args.includes('--todo')) { console.log(`photo slots: ${slots.count} (generated/slots.json)`); return; }
  const photos = read(join(HERE, 'photos.json')).photos;
  const missing = slots.slots.filter(s => !processed(photos[s.slot]));
  if (args.includes('--todo')) {
    for (const s of missing) console.log(JSON.stringify({ slot: s.slot, search: s.query, use: s.use }));
    return;
  }
  const byGroup = Map.groupBy(missing, s => s.group);
  for (const [group, list] of byGroup) {
    console.log(`\n${group} (${list.length} without a photo)`);
    for (const s of list) console.log(`  ${s.slot.padEnd(66)} search: ${s.query}${s.fallback ? `   [meanwhile: ${s.fallback}]` : ''}`);
  }
  console.log(`\n${missing.length} of ${slots.count} slots have no photo yet${missing.length ? ' (each shows its fallback, finally the drawn picture)' : ''}.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main(process.argv.slice(2));
