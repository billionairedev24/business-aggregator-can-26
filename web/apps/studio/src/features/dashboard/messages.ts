const WORDS: Record<Locale, readonly string[]> = {
  en: ['No', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine', 'Ten'],
  fr: ['Aucune', 'Une', 'Deux', 'Trois', 'Quatre', 'Cinq', 'Six', 'Sept', 'Huit', 'Neuf', 'Dix'],
};

/** "Three" at the start of the headline, "three" inside it; digits above ten. */
export function numberWord(n: number, locale: Locale, capital: boolean): string {
  const w = WORDS[locale][n];
  if (w === undefined) return String(n);
  return capital ? w : w.toLowerCase();
}
